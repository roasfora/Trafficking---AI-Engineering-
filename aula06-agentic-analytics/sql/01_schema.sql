-- Corre automaticamente na primeira vez que o container arranca
-- (docker-entrypoint-initdb.d), como superuser "analytics".
-- Para repetir: docker compose down -v && docker compose up -d

CREATE SCHEMA marketing;

-- Grain: 1 linha = 1 data + 1 provider + 1 campanha.
CREATE TABLE marketing.campaign_performance_daily (
    date          DATE          NOT NULL,
    provider      TEXT          NOT NULL CHECK (provider IN ('trafficjunky', 'erobella')),
    campaign_name TEXT          NOT NULL,
    campaign_id   TEXT          NOT NULL,
    currency      TEXT          NOT NULL CHECK (currency = 'EUR'),
    impressions   BIGINT        NOT NULL CHECK (impressions >= 0),
    clicks        BIGINT        NOT NULL CHECK (clicks >= 0),
    cost          NUMERIC(12,2) NOT NULL CHECK (cost >= 0),
    conversions   BIGINT        NOT NULL CHECK (conversions >= 0),
    revenue       NUMERIC(12,2) NOT NULL CHECK (revenue >= 0),
    PRIMARY KEY (date, provider, campaign_id),
    CHECK (clicks <= impressions),
    CHECK (conversions <= clicks)
);

-- Metadata TECNICA: e isto que a tool get_dataset_metadata le do catalogo.
COMMENT ON TABLE marketing.campaign_performance_daily IS
    'Daily advertising performance aggregated by date, provider and campaign.';

COMMENT ON COLUMN marketing.campaign_performance_daily.date          IS 'Campaign performance date.';
COMMENT ON COLUMN marketing.campaign_performance_daily.provider      IS 'Traffic source that generated the advertising investment.';
COMMENT ON COLUMN marketing.campaign_performance_daily.campaign_name IS 'Human-readable advertising campaign name.';
COMMENT ON COLUMN marketing.campaign_performance_daily.campaign_id   IS 'Unique identifier of the advertising campaign.';
COMMENT ON COLUMN marketing.campaign_performance_daily.currency      IS 'Currency used for advertising spend and revenue.';
COMMENT ON COLUMN marketing.campaign_performance_daily.impressions   IS 'Number of times the advertisement was displayed.';
COMMENT ON COLUMN marketing.campaign_performance_daily.clicks        IS 'Number of clicks generated by the campaign.';
COMMENT ON COLUMN marketing.campaign_performance_daily.cost          IS 'Advertising spend for the campaign and day.';
COMMENT ON COLUMN marketing.campaign_performance_daily.conversions   IS 'Number of conversions attributed to the campaign.';
COMMENT ON COLUMN marketing.campaign_performance_daily.revenue       IS 'Revenue attributed to the campaign and day.';

-- Utilizador do agente: so le UMA tabela. Ultima linha de defesa:
-- mesmo que o prompt e o SQL guard falhassem, a base de dados recusa.
-- (Password de desenvolvimento local; em producao vem de um secret manager.)
CREATE ROLE analytics_agent LOGIN PASSWORD 'agent_dev'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;

GRANT CONNECT ON DATABASE analytics TO analytics_agent;
GRANT USAGE ON SCHEMA marketing TO analytics_agent;
GRANT SELECT ON marketing.campaign_performance_daily TO analytics_agent;

ALTER ROLE analytics_agent SET default_transaction_read_only = on;
